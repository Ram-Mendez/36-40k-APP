-- V1__catalog_audit.sql
CREATE TABLE customer (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(200) NOT NULL,
 tax_id varchar(32) NOT NULL UNIQUE,
 email varchar(254) NOT NULL,
 address varchar(500) NOT NULL,
 active boolean NOT NULL DEFAULT true,
 version bigint NOT NULL DEFAULT 0
);
CREATE INDEX ix_customer_active_name ON customer(active,name,id);
CREATE TABLE product (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sku varchar(64) NOT NULL UNIQUE,
 name varchar(200) NOT NULL,
 unit_price numeric(14,2) NOT NULL CHECK (unit_price > 0),
 active boolean NOT NULL DEFAULT true,
 version bigint NOT NULL DEFAULT 0
);
CREATE INDEX ix_product_active_name ON product(active,name,id);
CREATE TABLE audit_event (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor varchar(100) NOT NULL,
 action varchar(80) NOT NULL,
 entity_type varchar(80) NOT NULL,
 entity_id varchar(80) NOT NULL,
 details varchar(2000) NOT NULL,
 request_id varchar(64),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_entity_created ON audit_event(entity_type,entity_id,created_at DESC,id DESC);

-- V3__orders_inventory.sql
CREATE TABLE inventory_balance (
    product_id bigint PRIMARY KEY REFERENCES product(id),
    on_hand bigint NOT NULL DEFAULT 0,
    reserved bigint NOT NULL DEFAULT 0,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT inventory_nonnegative CHECK (on_hand >= reserved AND reserved >= 0)
);
CREATE TABLE sales_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customer(id),
    status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','CONFIRMED','COMPLETED','CANCELLED')),
    total numeric(14,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    version bigint NOT NULL DEFAULT 0,
    shipping_reference varchar(100),
    shipping_cost numeric(14,2) CHECK (shipping_cost >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE order_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES sales_order(id),
    product_id bigint NOT NULL REFERENCES product(id),
    quantity bigint NOT NULL CHECK (quantity > 0 AND quantity <= 1000000),
    unit_price numeric(14,2) NOT NULL CHECK (unit_price >= 0),
    UNIQUE(order_id, product_id)
);
CREATE TABLE stock_reservation (
    order_id bigint NOT NULL REFERENCES sales_order(id),
    product_id bigint NOT NULL REFERENCES product(id),
    quantity bigint NOT NULL CHECK (quantity > 0),
    PRIMARY KEY(order_id, product_id)
);
CREATE TABLE stock_movement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES product(id),
    order_id bigint REFERENCES sales_order(id),
    kind varchar(20) NOT NULL CHECK (kind IN ('ADJUSTMENT','RESERVE','RELEASE','SHIP')),
    quantity bigint NOT NULL CHECK (quantity <> 0),
    reason varchar(500) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_order_customer_created ON sales_order(customer_id, created_at DESC);
CREATE INDEX ix_order_status_created ON sales_order(status, created_at DESC);
CREATE INDEX ix_line_product ON order_line(product_id);
CREATE INDEX ix_reservation_product ON stock_reservation(product_id);
CREATE INDEX ix_movement_product_created ON stock_movement(product_id, created_at DESC);

-- V5__procurement.sql
CREATE TABLE supplier (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    tax_id varchar(32) NOT NULL UNIQUE,
    email varchar(254) NOT NULL,
    lead_time_days integer NOT NULL CHECK (lead_time_days BETWEEN 0 AND 365),
    active boolean NOT NULL DEFAULT true,
    version bigint NOT NULL DEFAULT 0
);
CREATE INDEX ix_supplier_active_name ON supplier(active, name, id);

CREATE TABLE purchase_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id bigint NOT NULL REFERENCES supplier(id),
    status varchar(24) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'SUBMITTED', 'PARTIALLY_RECEIVED', 'RECEIVED', 'CANCELLED')),
    expected_on date NOT NULL,
    total numeric(14,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    version bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_purchase_supplier_created ON purchase_order(supplier_id, created_at DESC, id DESC);
CREATE INDEX ix_purchase_status_expected ON purchase_order(status, expected_on, id);

CREATE TABLE purchase_order_line (
    purchase_order_id bigint NOT NULL REFERENCES purchase_order(id),
    product_id bigint NOT NULL REFERENCES product(id),
    quantity bigint NOT NULL CHECK (quantity BETWEEN 1 AND 1000000),
    received_quantity bigint NOT NULL DEFAULT 0,
    unit_cost numeric(14,2) NOT NULL CHECK (unit_cost > 0),
    PRIMARY KEY(purchase_order_id, product_id),
    CHECK (received_quantity BETWEEN 0 AND quantity)
);
CREATE INDEX ix_purchase_line_product ON purchase_order_line(product_id);

CREATE TABLE purchase_receipt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint NOT NULL REFERENCES purchase_order(id),
    request_id uuid NOT NULL,
    payload_hash char(64) NOT NULL,
    delivery_reference varchar(120) NOT NULL,
    received_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(purchase_order_id, request_id),
    UNIQUE(id, purchase_order_id)
);
CREATE INDEX ix_receipt_order_created ON purchase_receipt(purchase_order_id, received_at DESC, id DESC);

CREATE TABLE purchase_receipt_line (
    receipt_id bigint NOT NULL,
    purchase_order_id bigint NOT NULL,
    product_id bigint NOT NULL,
    quantity bigint NOT NULL CHECK (quantity BETWEEN 1 AND 1000000),
    PRIMARY KEY(receipt_id, product_id),
    FOREIGN KEY(receipt_id, purchase_order_id) REFERENCES purchase_receipt(id, purchase_order_id),
    FOREIGN KEY(purchase_order_id, product_id) REFERENCES purchase_order_line(purchase_order_id, product_id)
);
CREATE INDEX ix_receipt_line_order_product ON purchase_receipt_line(purchase_order_id, product_id);

ALTER TABLE stock_movement DROP CONSTRAINT stock_movement_kind_check;
ALTER TABLE stock_movement ADD CONSTRAINT stock_movement_kind_check
    CHECK (kind IN ('ADJUSTMENT', 'RESERVE', 'RELEASE', 'SHIP', 'RECEIPT', 'RETURN'));

-- V6__sales_returns.sql
CREATE TABLE sales_return (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES sales_order(id),
    status varchar(20) NOT NULL DEFAULT 'REQUESTED'
        CHECK (status IN ('REQUESTED','APPROVED','REJECTED','RECEIVED')),
    reason varchar(500) NOT NULL CHECK (length(btrim(reason)) > 0),
    review_reason varchar(500),
    credit_amount numeric(14,2) NOT NULL CHECK (credit_amount >= 0),
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    create_request_id uuid NOT NULL,
    create_fingerprint varchar(64) NOT NULL,
    receipt_request_id uuid,
    receipt_fingerprint varchar(64),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    reviewed_at timestamptz,
    received_at timestamptz,
    UNIQUE (order_id, create_request_id),
    CONSTRAINT sales_return_review_check CHECK (
        (status = 'REQUESTED' AND review_reason IS NULL AND reviewed_at IS NULL)
        OR (status <> 'REQUESTED' AND review_reason IS NOT NULL AND reviewed_at IS NOT NULL)
    ),
    CONSTRAINT sales_return_receipt_check CHECK (
        (status = 'RECEIVED' AND receipt_request_id IS NOT NULL
            AND receipt_fingerprint IS NOT NULL AND received_at IS NOT NULL)
        OR (status <> 'RECEIVED' AND receipt_request_id IS NULL
            AND receipt_fingerprint IS NULL AND received_at IS NULL)
    )
);

CREATE TABLE sales_return_line (
    return_id bigint NOT NULL REFERENCES sales_return(id),
    product_id bigint NOT NULL REFERENCES product(id),
    quantity bigint NOT NULL CHECK (quantity BETWEEN 1 AND 1000000),
    unit_price numeric(14,2) NOT NULL CHECK (unit_price >= 0),
    restock_quantity bigint CHECK (restock_quantity >= 0),
    damaged_quantity bigint CHECK (damaged_quantity >= 0),
    PRIMARY KEY (return_id, product_id),
    CONSTRAINT sales_return_line_disposition_check CHECK (
        (restock_quantity IS NULL AND damaged_quantity IS NULL)
        OR (restock_quantity IS NOT NULL AND damaged_quantity IS NOT NULL
            AND restock_quantity + damaged_quantity = quantity)
    )
);

CREATE INDEX ix_return_order_status ON sales_return(order_id, status, id);
CREATE INDEX ix_return_status_created ON sales_return(status, created_at DESC, id DESC);
CREATE INDEX ix_return_line_product ON sales_return_line(product_id, return_id);

-- V7__billing.sql
CREATE TABLE invoice (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL UNIQUE REFERENCES sales_order(id),
    customer_id bigint NOT NULL REFERENCES customer(id),
    customer_name varchar(200) NOT NULL,
    customer_tax_id varchar(32) NOT NULL,
    customer_address varchar(500) NOT NULL,
    product_total numeric(14,2) NOT NULL CHECK (product_total >= 0),
    shipping_total numeric(14,2) NOT NULL CHECK (shipping_total >= 0),
    currency char(3) NOT NULL DEFAULT 'EUR' CHECK (currency = 'EUR'),
    due_date date NOT NULL,
    issued_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_invoice_customer_due ON invoice(customer_id, due_date, id);
CREATE INDEX ix_invoice_due ON invoice(due_date, id);

CREATE TABLE invoice_entry (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id bigint NOT NULL REFERENCES invoice(id),
    request_id uuid NOT NULL,
    kind varchar(10) NOT NULL CHECK (kind IN ('PAYMENT', 'REFUND')),
    amount numeric(14,2) NOT NULL CHECK (amount > 0),
    reference varchar(120) NOT NULL CHECK (length(trim(reference)) > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    reversed_at timestamptz,
    reversal_reason varchar(500),
    UNIQUE(invoice_id, request_id),
    CHECK ((reversed_at IS NULL AND reversal_reason IS NULL)
        OR (reversed_at IS NOT NULL AND length(trim(reversal_reason)) > 0))
);
CREATE INDEX ix_invoice_entry_created ON invoice_entry(invoice_id, created_at, id);

-- V8__replenishment.sql
CREATE TABLE replenishment_policy (
    product_id bigint PRIMARY KEY REFERENCES product(id),
    minimum_stock bigint NOT NULL CHECK (minimum_stock BETWEEN 0 AND 1000000000),
    target_stock bigint NOT NULL CHECK (target_stock BETWEEN 0 AND 1000000000),
    preferred_supplier_id bigint REFERENCES supplier(id),
    active boolean NOT NULL DEFAULT true,
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (target_stock >= minimum_stock)
);
CREATE INDEX ix_replenishment_supplier_product
    ON replenishment_policy(preferred_supplier_id, product_id);
