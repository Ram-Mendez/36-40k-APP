CREATE TABLE customer (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(200) NOT NULL,
 tax_id varchar(32) NOT NULL UNIQUE,
 email varchar(254) NOT NULL,
 address varchar(500) NOT NULL,
 active boolean NOT NULL DEFAULT true,
 version bigint NOT NULL DEFAULT 0
);
CREATE INDEX ix_customer_active_name ON customer(active,name,id);
CREATE TABLE product (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sku varchar(64) NOT NULL UNIQUE,
 name varchar(200) NOT NULL,
 unit_price numeric(14,2) NOT NULL CHECK (unit_price > 0),
 active boolean NOT NULL DEFAULT true,
 version bigint NOT NULL DEFAULT 0
);
CREATE INDEX ix_product_active_name ON product(active,name,id);
CREATE TABLE audit_event (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 actor varchar(100) NOT NULL,
 action varchar(80) NOT NULL,
 entity_type varchar(80) NOT NULL,
 entity_id varchar(80) NOT NULL,
 details varchar(2000) NOT NULL,
 request_id varchar(64),
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_entity_created ON audit_event(entity_type,entity_id,created_at DESC,id DESC);
