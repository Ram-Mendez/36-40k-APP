CREATE TABLE inventory_balance (
    product_id bigint PRIMARY KEY REFERENCES product(id),
    on_hand bigint NOT NULL DEFAULT 0,
    reserved bigint NOT NULL DEFAULT 0,
    version bigint NOT NULL DEFAULT 0,
    CONSTRAINT inventory_nonnegative CHECK (on_hand >= reserved AND reserved >= 0)
);
CREATE TABLE sales_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customer(id),
    status varchar(20) NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','CONFIRMED','COMPLETED','CANCELLED')),
    total numeric(14,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    version bigint NOT NULL DEFAULT 0,
    shipping_reference varchar(100),
    shipping_cost numeric(14,2) CHECK (shipping_cost >= 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE order_line (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES sales_order(id),
    product_id bigint NOT NULL REFERENCES product(id),
    quantity bigint NOT NULL CHECK (quantity > 0 AND quantity <= 1000000),
    unit_price numeric(14,2) NOT NULL CHECK (unit_price >= 0),
    UNIQUE(order_id, product_id)
);
CREATE TABLE stock_reservation (
    order_id bigint NOT NULL REFERENCES sales_order(id),
    product_id bigint NOT NULL REFERENCES product(id),
    quantity bigint NOT NULL CHECK (quantity > 0),
    PRIMARY KEY(order_id, product_id)
);
CREATE TABLE stock_movement (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES product(id),
    order_id bigint REFERENCES sales_order(id),
    kind varchar(20) NOT NULL CHECK (kind IN ('ADJUSTMENT','RESERVE','RELEASE','SHIP')),
    quantity bigint NOT NULL CHECK (quantity <> 0),
    reason varchar(500) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_order_customer_created ON sales_order(customer_id, created_at DESC);
CREATE INDEX ix_order_status_created ON sales_order(status, created_at DESC);
CREATE INDEX ix_line_product ON order_line(product_id);
CREATE INDEX ix_reservation_product ON stock_reservation(product_id);
CREATE INDEX ix_movement_product_created ON stock_movement(product_id, created_at DESC);
