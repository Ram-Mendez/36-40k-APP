CREATE TABLE supplier (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    tax_id varchar(32) NOT NULL UNIQUE,
    email varchar(254) NOT NULL,
    lead_time_days integer NOT NULL CHECK (lead_time_days BETWEEN 0 AND 365),
    active boolean NOT NULL DEFAULT true,
    version bigint NOT NULL DEFAULT 0
);
CREATE INDEX ix_supplier_active_name ON supplier(active, name, id);

CREATE TABLE purchase_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id bigint NOT NULL REFERENCES supplier(id),
    status varchar(24) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'SUBMITTED', 'PARTIALLY_RECEIVED', 'RECEIVED', 'CANCELLED')),
    expected_on date NOT NULL,
    total numeric(14,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    version bigint NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_purchase_supplier_created ON purchase_order(supplier_id, created_at DESC, id DESC);
CREATE INDEX ix_purchase_status_expected ON purchase_order(status, expected_on, id);

CREATE TABLE purchase_order_line (
    purchase_order_id bigint NOT NULL REFERENCES purchase_order(id),
    product_id bigint NOT NULL REFERENCES product(id),
    quantity bigint NOT NULL CHECK (quantity BETWEEN 1 AND 1000000),
    received_quantity bigint NOT NULL DEFAULT 0,
    unit_cost numeric(14,2) NOT NULL CHECK (unit_cost > 0),
    PRIMARY KEY(purchase_order_id, product_id),
    CHECK (received_quantity BETWEEN 0 AND quantity)
);
CREATE INDEX ix_purchase_line_product ON purchase_order_line(product_id);

CREATE TABLE purchase_receipt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id bigint NOT NULL REFERENCES purchase_order(id),
    request_id uuid NOT NULL,
    payload_hash char(64) NOT NULL,
    delivery_reference varchar(120) NOT NULL,
    received_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(purchase_order_id, request_id),
    UNIQUE(id, purchase_order_id)
);
CREATE INDEX ix_receipt_order_created ON purchase_receipt(purchase_order_id, received_at DESC, id DESC);

CREATE TABLE purchase_receipt_line (
    receipt_id bigint NOT NULL,
    purchase_order_id bigint NOT NULL,
    product_id bigint NOT NULL,
    quantity bigint NOT NULL CHECK (quantity BETWEEN 1 AND 1000000),
    PRIMARY KEY(receipt_id, product_id),
    FOREIGN KEY(receipt_id, purchase_order_id) REFERENCES purchase_receipt(id, purchase_order_id),
    FOREIGN KEY(purchase_order_id, product_id) REFERENCES purchase_order_line(purchase_order_id, product_id)
);
CREATE INDEX ix_receipt_line_order_product ON purchase_receipt_line(purchase_order_id, product_id);

