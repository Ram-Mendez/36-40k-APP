CREATE TABLE sales_return (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES sales_order(id),
    status varchar(20) NOT NULL DEFAULT 'REQUESTED'
        CHECK (status IN ('REQUESTED','APPROVED','REJECTED','RECEIVED')),
    reason varchar(500) NOT NULL CHECK (length(btrim(reason)) > 0),
    review_reason varchar(500),
    credit_amount numeric(14,2) NOT NULL CHECK (credit_amount >= 0),
    version bigint NOT NULL DEFAULT 0 CHECK (version >= 0),
    create_request_id uuid NOT NULL,
    create_fingerprint varchar(64) NOT NULL,
    receipt_request_id uuid,
    receipt_fingerprint varchar(64),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    reviewed_at timestamptz,
    received_at timestamptz,
    UNIQUE (order_id, create_request_id),
    CONSTRAINT sales_return_review_check CHECK (
        (status = 'REQUESTED' AND review_reason IS NULL AND reviewed_at IS NULL)
        OR (status <> 'REQUESTED' AND review_reason IS NOT NULL AND reviewed_at IS NOT NULL)
    ),
    CONSTRAINT sales_return_receipt_check CHECK (
        (status = 'RECEIVED' AND receipt_request_id IS NOT NULL
            AND receipt_fingerprint IS NOT NULL AND received_at IS NOT NULL)
        OR (status <> 'RECEIVED' AND receipt_request_id IS NULL
            AND receipt_fingerprint IS NULL AND received_at IS NULL)
    )
);

CREATE TABLE sales_return_line (
    return_id bigint NOT NULL REFERENCES sales_return(id),
    product_id bigint NOT NULL REFERENCES product(id),
    quantity bigint NOT NULL CHECK (quantity BETWEEN 1 AND 1000000),
    unit_price numeric(14,2) NOT NULL CHECK (unit_price >= 0),
    restock_quantity bigint CHECK (restock_quantity >= 0),
    damaged_quantity bigint CHECK (damaged_quantity >= 0),
    PRIMARY KEY (return_id, product_id),
    CONSTRAINT sales_return_line_disposition_check CHECK (
        (restock_quantity IS NULL AND damaged_quantity IS NULL)
        OR (restock_quantity IS NOT NULL AND damaged_quantity IS NOT NULL
            AND restock_quantity + damaged_quantity = quantity)
    )
);

CREATE INDEX ix_return_order_status ON sales_return(order_id, status, id);
CREATE INDEX ix_return_status_created ON sales_return(status, created_at DESC, id DESC);
CREATE INDEX ix_return_line_product ON sales_return_line(product_id, return_id);
