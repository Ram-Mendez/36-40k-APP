CREATE TABLE invoice (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL UNIQUE REFERENCES sales_order(id),
    customer_id bigint NOT NULL REFERENCES customer(id),
    customer_name varchar(200) NOT NULL,
    customer_tax_id varchar(32) NOT NULL,
    customer_address varchar(500) NOT NULL,
    product_total numeric(14,2) NOT NULL CHECK (product_total >= 0),
    shipping_total numeric(14,2) NOT NULL CHECK (shipping_total >= 0),
    currency char(3) NOT NULL DEFAULT 'EUR' CHECK (currency = 'EUR'),
    due_date date NOT NULL,
    issued_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_invoice_customer_due ON invoice(customer_id, due_date, id);
CREATE INDEX ix_invoice_due ON invoice(due_date, id);

CREATE TABLE invoice_entry (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id bigint NOT NULL REFERENCES invoice(id),
    request_id uuid NOT NULL,
    kind varchar(10) NOT NULL CHECK (kind IN ('PAYMENT', 'REFUND')),
    amount numeric(14,2) NOT NULL CHECK (amount > 0),
    reference varchar(120) NOT NULL CHECK (length(trim(reference)) > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    reversed_at timestamptz,
    reversal_reason varchar(500),
    UNIQUE(invoice_id, request_id),
    CHECK ((reversed_at IS NULL AND reversal_reason IS NULL)
        OR (reversed_at IS NOT NULL AND length(trim(reversal_reason)) > 0))
);
CREATE INDEX ix_invoice_entry_created ON invoice_entry(invoice_id, created_at, id);
