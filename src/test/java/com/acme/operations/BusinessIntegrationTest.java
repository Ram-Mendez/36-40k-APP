    // Send a request with authentication and check the expected HTTP status.
    private JsonNode call(MockHttpServletRequestBuilder request, Object body, int expectedStatus)
            throws Exception {
        // Attach the token to the request prepared by each test.
        request.header("Authorization", bearer);
        // If there is a body, it converts it to JSON; a request without a body adds no content.
        if (body != null)
            request.contentType(MediaType.APPLICATION_JSON).content(mapper.writeValueAsBytes(body));
        // Run the request through MockMvc and get the answer from Spring.
        var result = mvc.perform(request).andReturn().getResponse();
        // If the state does not match, it also shows the body to facilitate the diagnosis.
        assertThat(result.getStatus())
                .withFailMessage("HTTP %s: %s", result.getStatus(), result.getContentAsString())
                .isEqualTo(expectedStatus);
        // For an empty response returns a null JSON node; if there is a body, he interprets it.
        return result.getContentAsString().isBlank()
                ? mapper.nullNode()
                : json(result.getContentAsString());
    }

