    // Repeat the stage three times to observe the concurrent reserve.
    @RepeatedTest(3)
    // Two orders compete for five units; each order four and only one can confirm.
    void competingOrdersCannotReserveSameUnits() throws Exception {
        // It creates a common stock and two orders for the same product.
        long product = product("10");
        adjust(product, 5);
        long customer = customer();
        long first = order(customer, product, 4);
        long second = order(customer, product, 4);
        // The barrier tries to get the two confirmations started at once.
        var barrier = new CyclicBarrier(2);
        // Use virtual threads to run the two requests in parallel.
        try (var executor = Executors.newVirtualThreadPerTaskExecutor()) {
            var responses =
                    // Each task awaits at the barrier and then confirms one of the orders.
                    executor.invokeAll(
                            List.of(
                                    () -> {
                                        barrier.await(10, TimeUnit.SECONDS);
                                        return mvc.perform(
                                                        post("/api/v1/orders/{id}/confirm", first)
                                                                .header("Authorization", bearer))
                                                .andReturn()
                                                .getResponse()
                                                .getStatus();
                                    },
                                    () -> {
                                        barrier.await(10, TimeUnit.SECONDS);
                                        return mvc.perform(
                                                        post("/api/v1/orders/{id}/confirm", second)
                                                                .header("Authorization", bearer))
                                                .andReturn()
                                                .getResponse()
                                                .getStatus();
                                    }));
            // One must receive 200 and the other 409, without assuming which one of them wins.
            assertThat(List.of(responses.get(0).get(), responses.get(1).get()))
                    .containsExactlyInAnyOrder(200, 409);
        }
        // Check the actual final state: five physicists and only four reserved.
        assertThat(balance(product, "on_hand")).isEqualTo(5);
        assertThat(balance(product, "reserved")).isEqualTo(4);
        // It contrasts reservations, confirmed orders and RESERE movements directly at the base.
        assertThat(
                        jdbc.queryForObject(
                                "SELECT sum(quantity) FROM stock_reservation WHERE product_id=?",
                                Long.class,
                                product))
                .isEqualTo(4);
        assertThat(
                        jdbc.queryForObject(
                                "SELECT count(*) FROM sales_order WHERE id IN (?,?) AND"
                                    + " status='CONFIRMED'",
                                Long.class,
                                first,
                                second))
                .isEqualTo(1);
        assertThat(
                        jdbc.queryForObject(
                                "SELECT count(*) FROM stock_movement WHERE product_id=? AND"
                                    + " kind='RESERVE'",
                                Long.class,
                                product))
                .isEqualTo(1);
    }

