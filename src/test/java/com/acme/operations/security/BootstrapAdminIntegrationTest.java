package com.acme.operations.security;

import static org.assertj.core.api.Assertions.*;

import com.acme.operations.AbstractIntegrationTest;
import com.acme.operations.common.AuditService;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.security.crypto.password.PasswordEncoder;
import org.springframework.transaction.annotation.Transactional;

// Spring ejecuta cada prueba en transacción; el marco de pruebas hace rollback al finalizar.
@Transactional
// Comprueba el alta inicial sobre PostgreSQL, aislando la tabla real de usuarios.
class BootstrapAdminIntegrationTest extends AbstractIntegrationTest {
    // Spring inyecta el codificador de producción y el servicio de auditoría de la prueba.
    @Autowired PasswordEncoder encoder;
    // Spring inyecta esta dependencia del contexto de pruebas.
    @Autowired AuditService audit;

    // Antes de cada caso crea una tabla temporal de usuarios vacía en la conexión transaccional.
    @BeforeEach
    void isolateEmptyUserTable() {
        // La tabla temporal oculta app_user real en esta conexión y se elimina al terminar la transacción.
        // PostgreSQL temp table shadows the real users only on this transaction's connection.
        jdbc.execute(
                "CREATE TEMP TABLE app_user (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY"
                    + " KEY, username varchar(80) NOT NULL UNIQUE,password_hash varchar(100) NOT"
                    + " NULL,role varchar(20) NOT NULL,active boolean NOT NULL DEFAULT"
                    + " true,created_at timestamptz NOT NULL DEFAULT current_timestamp) ON COMMIT"
                    + " DROP");
    }

    // Con tabla vacía crea un administrador; ejecutarlo otra vez no debe reemplazarlo.
    @Test
    void provisionsEmptyDatabaseOnceWithoutResettingExistingAdministrator() {
        // Construye el inicializador con credenciales de ejemplo y lo ejecuta manualmente.
        var initializer =
                new BootstrapAdminInitializer(
                        jdbc, encoder, audit, "FirstAdmin", "ProductionPassword789!");
        initializer.run(null);
        // Comprueba que hay una sola cuenta con nombre normalizado y rol ADMIN.
        assertThat(jdbc.queryForObject("SELECT count(*) FROM app_user", Long.class)).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT username FROM app_user", String.class))
                .isEqualTo("firstadmin");
        assertThat(jdbc.queryForObject("SELECT role FROM app_user", String.class))
                .isEqualTo("ADMIN");
        // Lee el hash y verifica la contraseña con PasswordEncoder; no compara texto en claro.
        String hash = jdbc.queryForObject("SELECT password_hash FROM app_user", String.class);
        assertThat(encoder.matches("ProductionPassword789!", hash)).isTrue();
        // Una segunda ejecución con otras credenciales debe dejar intacta la cuenta anterior.
        new BootstrapAdminInitializer(jdbc, encoder, audit, "other", "AnotherPassword789!")
                .run(null);
        assertThat(jdbc.queryForObject("SELECT count(*) FROM app_user", Long.class)).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT password_hash FROM app_user", String.class))
                .isEqualTo(hash);
    }

    // La contraseña de desarrollo no es válida para aprovisionar al primer administrador.
    @Test
    void refusesDevelopmentPasswordAndLeavesDatabaseEmpty() {
        // Prepara el inicializador con esa contraseña prohibida.
        var initializer =
                new BootstrapAdminInitializer(
                        jdbc, encoder, audit, "initialadmin", "DevPassword123!");
        // Exige IllegalStateException y comprueba que no se creó ninguna cuenta.
        assertThatIllegalStateException().isThrownBy(() -> initializer.run(null));
        assertThat(jdbc.queryForObject("SELECT count(*) FROM app_user", Long.class)).isZero();
    }
}
